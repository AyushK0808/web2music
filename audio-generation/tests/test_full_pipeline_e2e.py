def test_sensitive_page_profile_makes_d_go_silent_instead_of_generating(pipeline_client):
    """
    Real-life edge case: a crisis-support page that B correctly detects as
    sensitive. B's privacy guarantee already held at recording time (see
    record_integration_fixtures_multi.js -- the LLM mock asserts it's never
    called for this page). B expresses "don't play anything here" via two
    signals on the Handoff-2 envelope: profile.mood == "silence" and a
    top-level isSilent: true / volume: 0.

    D now defends itself against this directly: /generate checks
    payload.isSilent and profile.sensitive_override before D2/D3/D4/D5 run
    at all, and short-circuits to a no-audio response. This is
    defense-in-depth, not a replacement for the caller-side check -- the
    ui/ extension's background.entry.js (handleHandoff2) already skips
    calling /generate entirely when isSilent is set, so in the real
    pipeline this path is a safety net for any other/future caller
    (Swagger, a direct API consumer) that forwards B's payload unfiltered.
    """
    real_handoff2 = _load_multi_fixture("sensitive_crisis_resource")
    assert real_handoff2["profile"]["mood"] == "silence", (
        "fixture no longer represents the sensitive/silence case -- "
        "regenerate it or update this test"
    )
    assert real_handoff2.get("isSilent") is True
    assert real_handoff2.get("volume") == 0
    assert real_handoff2["profile"]["sensitive_override"] is True

    response = pipeline_client.post("/generate", json=real_handoff2)

    assert response.status_code == 200
    body = response.json()

    assert body["cache"] == "skip"
    assert body["audio_url"] is None
    assert body["metadata"]["is_silent"] is True
    assert body["metadata"]["sensitive_override"] is True
    assert body["metadata"]["is_fallback"] is False

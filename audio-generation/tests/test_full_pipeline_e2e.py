def test_real_b_payload_produces_a_playable_clip_end_to_end(pipeline_client, real_handoff2):
    """
    The core end-to-end assertion: B's real Handoff-2 payload, posted
    exactly as B would send it, comes back from the real /generate app as
    a cache-miss with a real audio_url and D4's loop metadata -- proving
    D1 (validate) -> D2 (prompt) -> D3 (generate, faked) -> D4 (process)
    -> D5 (cache, faked) all connect correctly on real data, not just each
    stage in isolation.
    """
    response = pipeline_client.post("/generate", json=real_handoff2)

    assert response.status_code == 200
    body = response.json()

    assert body["cache"] == "miss"
    assert body["metadata"]["is_fallback"] is False
    assert body["audio_url"]

    expected = real_handoff2["profile"]
    assert body["metadata"]["mood"] == expected["mood"]
    assert body["metadata"]["bpm"] == expected["bpm"]
    assert body["metadata"]["key"] == expected["key"]

    # D4's loop metadata must have made it all the way through
    assert isinstance(body["metadata"]["loop_point_ms"], int)
    assert body["metadata"]["loop_point_ms"] > 0
    assert "energy_delta_db" in body["metadata"]["seam_discontinuity"]

    # D2 should have used B's real prompt, not rebuilt its own fallback
    assert body["metadata"]["prompt_used"] == real_handoff2["prompt"]
    assert body["metadata"]["prompt_source"] == "feature_b"


def test_real_b_payload_is_cached_on_second_request(pipeline_client, real_handoff2):
    """Posting the same real B payload twice should hit the cache the
    second time, with the same audio_url and loop_point_ms as the first
    (real) generation -- proving make_cache_key() produces a stable key
    from B's actual field values, not just from hand-typed test data."""
    first = pipeline_client.post("/generate", json=real_handoff2).json()
    second = pipeline_client.post("/generate", json=real_handoff2).json()

    assert first["cache"] == "miss"
    assert second["cache"] == "hit"
    assert second["audio_url"] == first["audio_url"]
    assert second["metadata"]["loop_point_ms"] == first["metadata"]["loop_point_ms"]


def test_pipeline_falls_back_gracefully_if_d3_generation_fails_on_real_profile(pipeline_client, real_handoff2, monkeypatch):
    """
    Same real B payload, but D3 (generation) fails -- confirms the
    fallback path (main.py's _fallback_response) still works correctly
    when fed B's real, non-trivial profile shape (nested instruments list,
    long style string, etc.), not just the simple hand-typed profiles the
    other fallback tests use.
    """
    import main as main_module
    from d3_generate import GenerationError

    async def failing_generate_audio(prompt, duration_seconds=28):
        raise GenerationError("simulated model failure")

    monkeypatch.setattr(main_module, "generate_audio", failing_generate_audio)

    def fake_get_fallback_clip(mood):
        return (
            b"fake fallback ogg bytes",
            {"loop_point_ms": 15000, "seam_discontinuity": None,
             "prompt_used": "fake prompt", "generation_seed": 11},
            f"{mood}.ogg",
        )

    monkeypatch.setattr(main_module, "get_fallback_clip", fake_get_fallback_clip)

    response = pipeline_client.post("/generate", json=real_handoff2)

    assert response.status_code == 200
    body = response.json()
    assert body["fallback"] is True
    assert body["metadata"]["is_fallback"] is True
    assert body["metadata"]["mood"] == real_handoff2["profile"]["mood"]
    assert real_handoff2["profile"]["mood"] in body["audio_url"]


